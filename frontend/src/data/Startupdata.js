// Helper to look up startup by name (case-insensitive, flexible)
export function findStartupData(name) {
  if (!name) return null;
  const key = name.toLowerCase().trim();
  // Direct match
  if (STARTUP_FINANCIAL_DATA[key]) return STARTUP_FINANCIAL_DATA[key];
  // Fuzzy: find first key that contains the search name or vice versa
  const found = Object.entries(STARTUP_FINANCIAL_DATA).find(([k]) =>
    k.includes(key) || key.includes(k) || k.replace(/[^a-z0-9]/g, "") === key.replace(/[^a-z0-9]/g, "")
  );
  return found ? found[1] : null;
}
